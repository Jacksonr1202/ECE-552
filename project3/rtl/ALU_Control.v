// Translate the opcode-level ALU class and instruction function fields into
// the four-bit operation code consumed by the ALU datapath.
module ALU_Control(
	input  wire [1:0] ALUOp,
	input  wire [2:0] Funct3,
	input  wire       Funct7,
	output reg  [3:0] ALUop
);
	// ALU operation encoding shared with the datapath.
	localparam [3:0] ALU_AND  = 4'b0000;
	localparam [3:0] ALU_OR   = 4'b0001;
	localparam [3:0] ALU_ADD  = 4'b0010;
	localparam [3:0] ALU_XOR  = 4'b0011;
	localparam [3:0] ALU_SLL  = 4'b0100;
	localparam [3:0] ALU_SRL  = 4'b0101;
	localparam [3:0] ALU_SUB  = 4'b0110;
	localparam [3:0] ALU_SLT  = 4'b0111;
	localparam [3:0] ALU_SLTU = 4'b1000;
	localparam [3:0] ALU_SRA  = 4'b1101;

	// ALUOp class values generated by OP_Control.
	localparam [1:0] ALU_CLASS_DEFAULT = 2'b00;
	localparam [1:0] ALU_CLASS_BRANCH  = 2'b01;
	localparam [1:0] ALU_CLASS_R_TYPE  = 2'b10;
	localparam [1:0] ALU_CLASS_I_TYPE  = 2'b11;

	always @(*) begin
		// ADD is the safe result for unused or unsupported control combinations.
		ALUop = ALU_ADD;

		case (ALUOp)
			ALU_CLASS_DEFAULT: ALUop = ALU_ADD;
			ALU_CLASS_BRANCH: ALUop = ALU_SUB;
			// R-type instructions use funct7[5] to distinguish SUB and SRA.
			ALU_CLASS_R_TYPE: begin
				case (Funct3)
					3'b000: ALUop = Funct7 ? ALU_SUB : ALU_ADD;
					3'b001: ALUop = ALU_SLL;
					3'b010: ALUop = ALU_SLT;
					3'b011: ALUop = ALU_SLTU;
					3'b100: ALUop = ALU_XOR;
					3'b101: ALUop = Funct7 ? ALU_SRA : ALU_SRL;
					3'b110: ALUop = ALU_OR;
					3'b111: ALUop = ALU_AND;
					default: ALUop = ALU_ADD;
				endcase
			end
			// I-type arithmetic always uses the immediate form; funct7 is not
			// interpreted as an R-type operation selector here.
			ALU_CLASS_I_TYPE: begin
				case (Funct3)
					3'b000: ALUop = ALU_ADD;
					3'b001: ALUop = ALU_SLL;
					3'b010: ALUop = ALU_SLT;
					3'b011: ALUop = ALU_SLTU;
					3'b100: ALUop = ALU_XOR;
					3'b101: ALUop = Funct7 ? ALU_SRA : ALU_SRL;
					3'b110: ALUop = ALU_OR;
					3'b111: ALUop = ALU_AND;
					default: ALUop = ALU_ADD;
				endcase
			end
			default: ALUop = ALU_ADD;
		endcase
	end
endmodule
